function clean(input) {
  const s = input && typeof input === 'object' ? input : {};
  const str = (v, d, max) => (typeof v === 'string' && v.trim() ? v.slice(0, max) : d);
  const num = (v, d, min, max) => (Number.isFinite(+v) ? Math.min(max, Math.max(min, Math.round(+v))) : d);
  return {
    role: str(s.role, DEFAULTS.role, LIMITS.role),
    rules: str(s.rules, DEFAULTS.rules, LIMITS.rules),
    company: str(s.company, DEFAULTS.company, LIMITS.company),
    model: /^[a-z0-9.\-]{3,60}$/i.test(String(s.model || '')) ? String(s.model) : DEFAULTS.model,
    maxTokens: num(s.maxTokens, DEFAULTS.maxTokens, 2000, 32000),
    thinking: s.thinking === true,
    webSearch: s.webSearch !== false,
    webSearchMax: num(s.webSearchMax, DEFAULTS.webSearchMax, 1, 15),
    domains: Array.isArray(s.domains)
      ? s.domains.map((d) => String(d).trim().replace(/^https?:\/\//, '').replace(/\/.*$/, '')).filter(Boolean).slice(0, 40)
      : DEFAULTS.domains,
    checklist: str(s.checklist, DEFAULTS.checklist, 30000),
    blanks: cleanBlanks(s.blanks),
    memory: cleanMemory(s.memory),
  };
}

