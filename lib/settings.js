function cleanMemory(list) {
  if (!Array.isArray(list)) return [];
  return list
    .filter((m) => m && typeof m === 'object' && typeof m.text === 'string' && m.text.trim())
    .slice(-400)
    .map((m) => ({
      id: String(m.id || '').slice(0, 40) || 'm' + Math.random().toString(36).slice(2, 10),
      text: String(m.text).trim().slice(0, 4000),
      ts: Number.isFinite(+m.ts) ? +m.ts : Date.now(),
      src: m.src === 'bot' ? 'bot' : 'user',
    }));
}

